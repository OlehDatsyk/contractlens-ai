function Fact({ label, value, evidence }: { label: string; value: ReactNode; evidence?: Evidence }) {
  const empty = value === null || value === undefined || value === ''
  return (
    <div className="border-b border-slate-100 py-3 last:border-0">
      <dt className="flex flex-wrap items-center gap-2 text-xs font-medium uppercase tracking-wide text-slate-500">
        {label}
        {!empty && evidence && <SourceBadge source={evidence.source} verified={evidence.verified || evidence.source === 'rule'} />}
      </dt>
      <dd className={cn('mt-1 text-sm', empty ? 'text-slate-400' : 'text-slate-900')}>{empty ? 'Not found in the document' : value}</dd>
      {!empty && evidence?.note && <p className="mt-1 text-xs text-amber-800">{evidence.note}</p>}
      {!empty && evidence?.quote && <EvidenceQuote className="mt-2" quote={evidence.quote} section={evidence.section} page={evidence.page} />}
    </div>
  )
}

